#!/usr/bin/env node
// Regenerate backend/src/chain/deployLedger.ts from the Foundry broadcast logs.
//
// The broadcast directory is the only record of every contract this project has
// ever put on chain, and it is committed. Hand-maintaining a second list of
// retired addresses would drift the first time somebody deployed without
// updating it, and the lifetime numbers would silently lose a generation. So
// the list is generated, and regenerating it is how a new deploy gets counted.
//
//   node scripts/gen-deploy-ledger.mjs
//
// Run it after any deploy, commit the result, and the all-time page picks the
// new contract up.

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BROADCAST = join(ROOT, 'contracts', 'broadcast');
const OUT = join(ROOT, 'backend', 'src', 'chain', 'deployLedger.ts');

/// Arc Testnet. Deploys to any other chain are somebody's local anvil and must
/// not end up in a number we publish.
const CHAIN_ID = 5042002;

/// Every Karwan contract whose history the lifetime scan covers, and the kind
/// of work each one does. The kind is what lets the page group a list of 50-odd
/// addresses into something a reader can scan.
///
/// The registries are here despite moving no USDC. They are still contracts we
/// operated, and their event counts are the activity behind the money: jobs
/// posted, reputation written, businesses registered. Leaving them out would
/// make "every contract" untrue, and a reader who checks the explorer would
/// find deployments the page never mentions.
///
/// MockUSYC is deliberately absent. It is a test double for Hashnote's token,
/// not a Karwan contract, and its transfers are not Karwan volume.
const TRACKED = new Map([
  ['KarwanEscrow', 'settlement'],
  ['KarwanVault', 'staking'],
  ['KarwanInvoiceRegistry', 'financing'],
  ['KarwanPOFinancing', 'financing'],
  ['KarwanTreasury', 'treasury'],
  ['KarwanYieldDistributor', 'treasury'],
  ['KarwanJobBoard', 'registry'],
  ['KarwanReputation', 'registry'],
  ['KarwanBusinessRegistry', 'registry'],
]);

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (entry.endsWith('.json')) out.push(p);
  }
  return out;
}

const found = new Map();

for (const file of walk(BROADCAST)) {
  let run;
  try {
    run = JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    continue; // a half-written or non-run json; the others carry the same data
  }
  if (Number(run.chain) !== CHAIN_ID) continue;

  // Deploy block comes from the receipt, not the transaction: the transaction
  // records what was sent, the receipt records where it landed. Scanning from
  // the deploy block instead of from chain genesis is the difference between a
  // few hundred getLogs windows and a few thousand.
  const blockByAddress = new Map();
  for (const r of run.receipts ?? []) {
    if (r.contractAddress && r.blockNumber) {
      blockByAddress.set(String(r.contractAddress).toLowerCase(), Number(BigInt(r.blockNumber)));
    }
  }

  for (const tx of run.transactions ?? []) {
    if (tx.transactionType !== 'CREATE') continue;
    if (!TRACKED.has(tx.contractName)) continue;
    const address = String(tx.contractAddress ?? '').toLowerCase();
    const block = blockByAddress.get(address);
    if (!address || !block) continue;
    // Same address twice means the same deploy recorded in run-latest and its
    // timestamped twin. Keep one.
    if (found.has(address)) continue;
    found.set(address, {
      name: tx.contractName,
      kind: TRACKED.get(tx.contractName),
      address,
      deployBlock: block,
      deployedAt: typeof run.timestamp === 'number' ? run.timestamp : null,
    });
  }
}

const rows = [...found.values()].sort((a, b) => a.deployBlock - b.deployBlock);
if (rows.length === 0) {
  console.error('no deployments found: is contracts/broadcast present and on chain', CHAIN_ID, '?');
  process.exit(1);
}

const body = rows
  .map(
    (r) =>
      `  { name: '${r.name}', kind: '${r.kind}', address: '${r.address}', deployBlock: ${r.deployBlock}n },`,
  )
  .join('\n');

const names = [...new Set(rows.map((r) => r.name))].sort();
const kinds = [...new Set(rows.map((r) => r.kind))].sort();

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-deploy-ledger.mjs from contracts/broadcast. Do not edit.
// Regenerate after any deploy so the all-time numbers include the new contract.

export type ContractName = ${names.map((n) => `'${n}'`).join(' | ')};

/// What the contract does, used to group the all-time breakdown. A page listing
/// fifty addresses with no grouping is a dump, not a report.
export type ContractKind = ${kinds.map((k) => `'${k}'`).join(' | ')};

export interface DeployedContract {
  name: ContractName;
  kind: ContractKind;
  address: \`0x\${string}\`;
  /// Block the CREATE landed in. The lifetime scan starts here rather than at
  /// genesis, which is what keeps the window count tractable.
  deployBlock: bigint;
}

/// Every Karwan contract ever deployed to Arc Testnet, oldest first. Retired
/// generations stay in this list on purpose: they are exactly what the all-time
/// totals exist to include.
export const DEPLOY_LEDGER: readonly DeployedContract[] = [
${body}
] as const;

export const ESCROW_DEPLOYMENTS = DEPLOY_LEDGER.filter((c) => c.name === 'KarwanEscrow');
export const VAULT_DEPLOYMENTS = DEPLOY_LEDGER.filter((c) => c.name === 'KarwanVault');
`,
  'utf8',
);

const byKind = new Map();
for (const r of rows) byKind.set(r.kind, (byKind.get(r.kind) ?? 0) + 1);

console.log(`wrote ${OUT}`);
console.log(`${rows.length} deployments across ${byKind.size} kinds:`);
for (const [kind, n] of [...byKind].sort()) {
  const forKind = rows.filter((r) => r.kind === kind);
  const detail = [...new Set(forKind.map((r) => r.name))]
    .map((name) => `${forKind.filter((r) => r.name === name).length} ${name.replace('Karwan', '')}`)
    .join(', ');
  console.log(`  ${kind.padEnd(11)} ${String(n).padStart(2)}  (${detail})`);
}
console.log(`earliest deploy block ${rows[0].deployBlock}`);
